function fav(url, size = 20) {
  const host = hostOf(url);
  const hit = FAVICONS.find(([re]) => re.test(host));
  const bg = hit ? hit[1] : `hsl(${hashStr(host) % 360} 45% 38%)`;
  const glyph = hit ? hit[2] : host.split(".").slice(-2, -1)[0]?.[0]?.toUpperCase() || "?";
  const fg = hit && hit[3] ? hit[3] : "#fff";
  const r = Math.round(size * 0.26);
  let inner;
  if (glyph === "github") inner = `<span style="width:${size * 0.7}px;height:${size * 0.7}px;color:${fg};display:block">${LOGOS.github()}</span>`;
  else if (glyph === "mongo") inner = `<span style="width:${size * 0.66}px;height:${size * 0.66}px;display:block">${LOGOS.mongo()}</span>`;
  else if (glyph === "atom") inner = fileIcon("x.tsx", Math.round(size * 0.72)).s;
  else {
    const fs = glyph.length > 2 ? size * 0.36 : glyph.length > 1 ? size * 0.42 : size * 0.56;
    inner = `<span style="font-size:${fs}px;color:${fg};line-height:1">${esc(glyph)}</span>`;
  }
  return raw(`<span class="fav" style="width:${size}px;height:${size}px;border-radius:${r}px;background:${bg}">${inner}</span>`);
}

